def _products(names: Iterable[str]) -> Tuple[str, ...]:
    result = []
    for name in names:
        result.append(name)
        result.extend(ALIASES.get(name, ()))
    return tuple(dict.fromkeys(x.lower().replace("_", "-") for x in result))


def _r(cid, name, severity, stack, products, ranges, fix, reference=None, confirm=True):
    """构造一条规则字典（字段与 VulnRule 一致）。"""
    if isinstance(products, str):
        products = (products,)
    if reference is None:
        reference = f"https://nvd.nist.gov/vuln/detail/{cid}" if cid.startswith("CVE-") else ""
    return {
        "id": cid,
        "name": name,
        "severity": severity,
        "category": stack,
        "products": _products(products),
        "ranges": tuple(tuple(pair) for pair in ranges),
        "remediation": fix,
        "reference": reference,
        "confirm": confirm,
    }


